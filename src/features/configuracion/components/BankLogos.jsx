/**
 * Componente wrapper que renderiza el logo según entidad ID
 */
export function BankLogo({ entidadId, className = 'h-8 w-8' }) {
  const id = entidadId?.toLowerCase()

  switch (id) {
    case 'santander':
      return <SantanderLogo className={className} />
    case 'bbva':
      return <BbvaLogo className={className} />
    case 'galicia':
      return <GaliciaLogo className={className} />
    case 'macro':
      return <MacroLogo className={className} />
    case 'nacion':
      return <NacionLogo className={className} />
    case 'provincia':
      return <ProvinciaLogo className={className} />
    case 'hsbc':
      return <HsbcLogo className={className} />
    case 'icbc':
      return <IcbcLogo className={className} />
    case 'ciudad':
      return <CiudadLogo className={className} />
    case 'itau':
      return <ItauLogo className={className} />
    case 'brubank':
      return <BrubankLogo className={className} />
    case 'reba':
      return <RebaLogo className={className} />
    case 'cencosud':
      return <CencosudLogo className={className} />
    case 'mercado_pago':
      return <MercadoPagoLogo className={className} />
    case 'uala':
      return <UalaLogo className={className} />
    case 'naranja_x':
      return <NaranjaXLogo className={className} />
    case 'personal_pay':
      return <PersonalPayLogo className={className} />
    case 'lemon_cash':
      return <LemonCashLogo className={className} />
    case 'belo':
      return <BeloLogo className={className} />
    case 'prex':
      return <PrexLogo className={className} />
    default:
      return <SantanderLogo className={className} />
  }
}
